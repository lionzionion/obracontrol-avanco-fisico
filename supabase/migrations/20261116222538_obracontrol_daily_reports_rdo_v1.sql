-- ObraControl / RL Engenharia - RDOs diários.
-- A geração lê obc_entries e obc_photos sem alterar os lançamentos ou BMs.
create table public.obc_rdos (
 id uuid primary key default gen_random_uuid(),
 rdo_no bigint generated by default as identity unique,
 work_date date not null unique,
 status text not null default 'draft' check(status in ('draft','final')),
 weather text not null default '',
 shift_description text not null default '',
 workforce text not null default '',
 equipment text not null default '',
 safety_notes text not null default '',
 occurrences text not null default '',
 general_notes text not null default '',
 engineer_name text not null default '',
 reviewer_name text not null default '',
 activities jsonb not null default '[]'::jsonb check(jsonb_typeof(activities)='array'),
 photo_manifest jsonb not null default '[]'::jsonb check(jsonb_typeof(photo_manifest)='array'),
 source_entry_ids jsonb not null default '[]'::jsonb check(jsonb_typeof(source_entry_ids)='array'),
 source_generated_at timestamptz,
 pdf_path text,
 created_by uuid not null default auth.uid() references auth.users(id),
 updated_by uuid references auth.users(id),
 finalized_by uuid references auth.users(id),
 finalized_at timestamptz,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 constraint obc_rdo_final_pdf check(status='draft' or (pdf_path is not null and finalized_at is not null)),
 constraint obc_rdo_field_length check(
   length(weather)<=150 and length(shift_description)<=200 and length(workforce)<=1500 and
   length(equipment)<=1500 and length(safety_notes)<=2500 and length(occurrences)<=3500 and
   length(general_notes)<=3500 and length(engineer_name)<=160 and length(reviewer_name)<=160
 )
);
create index obc_rdos_date_idx on public.obc_rdos(work_date desc);
alter table public.obc_rdos enable row level security;
revoke all on public.obc_rdos from anon,authenticated;
grant select,insert,update on public.obc_rdos to authenticated;
grant usage,select on sequence public.obc_rdos_rdo_no_seq to authenticated;

create policy obc_rdo_team_read on public.obc_rdos for select to authenticated
using (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.active and p.role in ('admin','colaborador')));
create policy obc_rdo_admin_insert on public.obc_rdos for insert to authenticated
with check(created_by=(select auth.uid()) and exists(
 select 1 from public.profiles p where p.id=(select auth.uid()) and p.active and p.role='admin'
));
create policy obc_rdo_admin_update on public.obc_rdos for update to authenticated
using (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.active and p.role='admin'))
with check(updated_by=(select auth.uid()) and exists(
 select 1 from public.profiles p where p.id=(select auth.uid()) and p.active and p.role='admin'
));

create function public.obc_rdo_revision_guard()
returns trigger language plpgsql set search_path = ''
as $$
begin
  if tg_op='UPDATE' then
    if old.status='final' then
      raise exception 'RDO finalizado nao pode ser editado. Preserve o PDF assinado/arquivado.';
    end if;
    if new.id is distinct from old.id or new.work_date is distinct from old.work_date
      or new.rdo_no is distinct from old.rdo_no or new.created_by is distinct from old.created_by
      or new.created_at is distinct from old.created_at then
      raise exception 'Nao e permitido alterar numero, data ou autoria original do RDO';
    end if;
  end if;
  if new.status='final' then
    if btrim(new.engineer_name)='' then
      raise exception 'Informe o nome do engenheiro responsavel antes de finalizar o RDO';
    end if;
    new.finalized_by=auth.uid();
    new.finalized_at=coalesce(new.finalized_at,now());
  else
    new.finalized_by=null;
    new.finalized_at=null;
    new.pdf_path=null;
  end if;
  new.updated_at=now();
  return new;
end;$$;
create trigger obc_rdo_revision_guard before insert or update on public.obc_rdos
 for each row execute function public.obc_rdo_revision_guard();

